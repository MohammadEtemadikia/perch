export const DICTS: Record<Locale, Record<string, string>> = { en, fa, nl };

export function intlLocale(locale: Locale): string {
  return locale === "fa" ? "fa-IR" : locale === "nl" ? "nl-NL" : "en-US";
}

export function translate(dict: Record<string, string>, key: string, vars?: Record<string, string | number>): string {
  let str = dict[key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.split(`{${k}}`).join(String(v));
    }
  }
  return str;
}
